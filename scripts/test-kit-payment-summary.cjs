const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), { createRequire, Module } = require("node:module");
const root = path.resolve(__dirname, ".."), web = createRequire(path.join(root, "artifacts/football-training-board/package.json"));
const folder = path.join(root, ".tools/kit-payment-summary"); fs.mkdirSync(folder, { recursive: true });
const esbuild = createRequire(web.resolve("vite"))("esbuild");
const load = (input, filename) => {
  const file = path.join(folder, filename + ".cjs");
  esbuild.buildSync({ entryPoints: [path.join(root, input)], outfile: file, bundle: true, platform: "node", format: "cjs", packages: "external", alias: { "@workspace/api-zod": path.join(root, "lib/api-zod/src/index.ts") } });
  const mod = new Module(file, module); mod.filename = file; mod.paths = [path.join(root, "lib/api-zod/node_modules")]; mod._compile(fs.readFileSync(file, "utf8"), file); return mod.exports;
};
const s = load("artifacts/football-training-board/src/lib/payment-summary.ts", "summary");
const k = load("lib/api-zod/src/player-kit-catalog.ts", "catalog");
const charges = { registration: 0, annual: 370, insurance: 25, shuttle: 0, kit: 0 };
const article = { paymentType: "kit_article", amount: 10, status: "paid" };
let result = s.playerEconomicBalance(charges, 0, [article], false, 0, false, true);
assert.equal(result.total, 405); assert.equal(result.alreadyPaid, 10); assert.equal(result.residual, 395);
assert.equal(result.planTotal, 395); assert.equal(result.planAlreadyPaid, 0);
assert.ok(!result.replaceTypes.includes("kit_article"), "individual articles must never be recreated by the total plan");
result = s.playerEconomicBalance(charges, 0, [{ ...article, status: "pending" }], false, 0, false, true);
assert.equal(result.total, 405); assert.equal(result.outstanding, 405); assert.equal(result.residual, 395);
assert.equal(result.planTotal, 395); assert.equal(result.planAlreadyPaid, 0);
const saved = { paymentType: "player_total_installment", amount: 395, annualFeeTotal: 395, status: "pending" };
result = s.playerEconomicBalance({ ...charges, annual: 0, insurance: 0 }, 0, [saved, article], true, 0, false);
assert.equal(result.total, 405); assert.equal(result.planTotal, 395); assert.equal(result.alreadyPaid, 10);
assert.equal(k.paymentKitSlot({ id: 1, name: "Kway senza capp." }), "k_way");
assert.equal(k.paymentKitSlot({ id: 1, name: "Kway senza capp.", kitSlots: [] }), "other", "explicit catalog mapping wins over name suggestions");
assert.equal(k.paymentKitSlot({ id: 1, name: "Pantalone rappresentanza" }), "rep_pants_sweatshirt:pants");
assert.equal(k.paymentKitSlot({ id: 1, name: "Articolo sconosciuto" }), "other");
assert.equal(k.isPaymentKitRow({ key: "payment:4", sourcePaymentId: 4 }), true);
assert.equal(k.isPaymentKitRow({ key: "payment:3", sourcePaymentId: 4 }), false);
assert.equal(k.isPaymentKitRow(null), false);
console.log("PASS kit payment summary: annual plan excludes independently registered articles, paid/pending balances, saved plans, shared catalog mapping and purchase identity");
